BEGIN;

-- Pesagens avulsas da balança: qualquer coisa que precise ser pesada e que
-- não é entrada nem saída de soja/milho. Ficam numa tabela própria para não
-- interferir nos saldos de armazenagem, contratos e relatórios.
--
-- Não há ordem fixa entre as pesagens (o veículo pode chegar cheio ou vazio),
-- por isso os pesos se chamam pesagem 1 e pesagem 2 e o peso líquido é a
-- diferença absoluta entre eles. Os campos de texto são livres e opcionais;
-- em branco a aplicação grava NULL.
CREATE TABLE IF NOT EXISTS public.pesagens_avulsas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa_caminhao character varying(10),
  nome_motorista character varying(120),
  produto character varying(120),
  vendedor character varying(120),
  comprador character varying(120),
  comentario text,
  pesagem_1_kg numeric NOT NULL,
  pesagem_1_em timestamp with time zone NOT NULL DEFAULT now(),
  pesagem_2_kg numeric,
  pesagem_2_em timestamp with time zone,
  peso_liquido_kg numeric GENERATED ALWAYS AS (abs(pesagem_2_kg - pesagem_1_kg)) STORED,
  criado_por_user_id uuid NOT NULL REFERENCES public.users(id),
  pesagem_2_por_user_id uuid REFERENCES public.users(id),
  criado_em timestamp with time zone NOT NULL DEFAULT now(),
  atualizado_em timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT pesagens_avulsas_pesagem_1_positiva_check CHECK (pesagem_1_kg > 0),
  CONSTRAINT pesagens_avulsas_pesagem_2_positiva_check CHECK (pesagem_2_kg IS NULL OR pesagem_2_kg > 0),
  -- Peso e data/hora da pesagem 2 entram e saem juntos.
  CONSTRAINT pesagens_avulsas_pesagem_2_completa_check CHECK ((pesagem_2_kg IS NULL) = (pesagem_2_em IS NULL)),
  CONSTRAINT pesagens_avulsas_placa_formato_check CHECK (placa_caminhao IS NULL OR placa_caminhao ~ '^[A-Z0-9]{1,10}$'),
  -- Um único representante de "não informado": NULL, nunca texto vazio.
  CONSTRAINT pesagens_avulsas_nome_motorista_preenchido_check CHECK (nome_motorista IS NULL OR btrim(nome_motorista) <> ''),
  CONSTRAINT pesagens_avulsas_produto_preenchido_check CHECK (produto IS NULL OR btrim(produto) <> ''),
  CONSTRAINT pesagens_avulsas_vendedor_preenchido_check CHECK (vendedor IS NULL OR btrim(vendedor) <> ''),
  CONSTRAINT pesagens_avulsas_comprador_preenchido_check CHECK (comprador IS NULL OR btrim(comprador) <> ''),
  CONSTRAINT pesagens_avulsas_comentario_check CHECK (comentario IS NULL OR (btrim(comentario) <> '' AND char_length(comentario) <= 1000))
);

COMMENT ON TABLE public.pesagens_avulsas IS
  'Pesagens avulsas da balança, fora do fluxo de entradas e saídas de grãos.';
COMMENT ON COLUMN public.pesagens_avulsas.placa_caminhao IS
  'Placa do veículo em maiúsculas, sem pontuação. Opcional e sem padrão fixo (até 10 letras/números).';
COMMENT ON COLUMN public.pesagens_avulsas.produto IS 'Texto livre opcional com o que foi pesado.';
COMMENT ON COLUMN public.pesagens_avulsas.vendedor IS 'Texto livre opcional.';
COMMENT ON COLUMN public.pesagens_avulsas.comprador IS 'Texto livre opcional.';
COMMENT ON COLUMN public.pesagens_avulsas.comentario IS
  'Anotação livre do operador, informada na pesagem 1 (até 1000 caracteres).';
COMMENT ON COLUMN public.pesagens_avulsas.pesagem_1_kg IS 'Primeira pesagem. Pode ser o veículo cheio ou vazio.';
COMMENT ON COLUMN public.pesagens_avulsas.pesagem_2_kg IS 'Segunda pesagem. NULL enquanto o veículo não voltou à balança.';
COMMENT ON COLUMN public.pesagens_avulsas.peso_liquido_kg IS
  'Diferença absoluta entre as duas pesagens, calculada pelo banco. NULL enquanto falta a pesagem 2.';
COMMENT ON COLUMN public.pesagens_avulsas.pesagem_2_por_user_id IS 'Operador que lançou a pesagem 2.';

CREATE INDEX IF NOT EXISTS pesagens_avulsas_pesagem_1_em_idx
  ON public.pesagens_avulsas (pesagem_1_em DESC, id DESC);

-- Pátio da balança: pesagens que ainda aguardam a pesagem 2.
CREATE INDEX IF NOT EXISTS pesagens_avulsas_pendentes_idx
  ON public.pesagens_avulsas (pesagem_1_em, id)
  WHERE pesagem_2_kg IS NULL;

-- Fotos da balança também podem ser vinculadas às pesagens avulsas, com os
-- tipos de peso pesagem_1 e pesagem_2. Como nas entradas e saídas, excluir a
-- pesagem não apaga a foto (ON DELETE SET NULL).
ALTER TABLE public.balanca_fotos
  ADD COLUMN IF NOT EXISTS pesagem_avulsa_id bigint
    REFERENCES public.pesagens_avulsas(id) ON DELETE SET NULL;

COMMENT ON COLUMN public.balanca_fotos.pesagem_avulsa_id IS
  'Pesagem avulsa à qual a captura foi vinculada. Vira NULL se a pesagem for excluída.';

CREATE INDEX IF NOT EXISTS balanca_fotos_pesagem_avulsa_idx
  ON public.balanca_fotos(pesagem_avulsa_id)
  WHERE pesagem_avulsa_id IS NOT NULL;

-- Constraint criada sem nome em 20261111_add_scale_photos.sql; o PostgreSQL
-- a nomeia balanca_fotos_tipo_peso_check.
ALTER TABLE public.balanca_fotos DROP CONSTRAINT IF EXISTS balanca_fotos_tipo_peso_check;
ALTER TABLE public.balanca_fotos
  ADD CONSTRAINT balanca_fotos_tipo_peso_check
  CHECK (tipo_peso IN ('bruto', 'tara', 'pesagem_1', 'pesagem_2'));

-- Bruto/tara só em entradas e saídas; pesagem_1/pesagem_2 só em avulsas. As
-- regras olham apenas a coluna preenchida, para continuar válidas depois que
-- o ON DELETE SET NULL limpa o vínculo.
ALTER TABLE public.balanca_fotos DROP CONSTRAINT IF EXISTS balanca_fotos_tipo_peso_registro_check;
ALTER TABLE public.balanca_fotos
  ADD CONSTRAINT balanca_fotos_tipo_peso_registro_check CHECK (
    (pesagem_avulsa_id IS NULL OR tipo_peso IN ('pesagem_1', 'pesagem_2'))
    AND ((entrada_id IS NULL AND saida_id IS NULL) OR tipo_peso IN ('bruto', 'tara'))
  );

ALTER TABLE public.balanca_fotos DROP CONSTRAINT IF EXISTS balanca_fotos_automatica_check;
ALTER TABLE public.balanca_fotos
  ADD CONSTRAINT balanca_fotos_automatica_check CHECK (
    origem <> 'automatica' OR (
      status IN ('recebida', 'substituida')
      AND chave_cliente IS NOT NULL
      AND entrada_id IS NULL AND saida_id IS NULL AND pesagem_avulsa_id IS NULL AND tipo_peso IS NULL
    )
  );

ALTER TABLE public.balanca_fotos DROP CONSTRAINT IF EXISTS balanca_fotos_temporaria_check;
ALTER TABLE public.balanca_fotos
  ADD CONSTRAINT balanca_fotos_temporaria_check CHECK (
    status <> 'temporaria' OR (
      expira_em IS NOT NULL
      AND entrada_id IS NULL AND saida_id IS NULL AND pesagem_avulsa_id IS NULL AND tipo_peso IS NULL
    )
  );

ALTER TABLE public.balanca_fotos DROP CONSTRAINT IF EXISTS balanca_fotos_um_registro_check;
ALTER TABLE public.balanca_fotos
  ADD CONSTRAINT balanca_fotos_um_registro_check
  CHECK (num_nonnulls(entrada_id, saida_id, pesagem_avulsa_id) <= 1);

COMMIT;
