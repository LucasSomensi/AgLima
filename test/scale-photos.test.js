function jpeg(text = 'frame') {
  return Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.from(text), Buffer.from([0xff, 0xd9])]);
}

function contingencyJpeg() {
  return Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xfe, 0x00, 0x20]), Buffer.from('AutoWeight:contingencia:manga'), Buffer.from([0xff, 0xd9])]);
}

function usePhotosDir(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'agrolima-fotos-'));
  const previous = process.env.FOTOS_DIR;
  process.env.FOTOS_DIR = dir;
  t.after(() => {
    if (previous === undefined) delete process.env.FOTOS_DIR;
    else process.env.FOTOS_DIR = previous;
    fs.rmSync(dir, { recursive: true, force: true });
  });
  return dir;
}

