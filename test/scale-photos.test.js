test('photos are served only to weighbridge users, as private JPEG', async (t) => {
  const dir = usePhotosDir(t);
  const arquivo = storage.buildStoredPhotoPath('capturas');
  await storage.writePhotoAtomically(arquivo, jpeg('servida'));
  const { cookie } = operatorSession(t);
  t.mock.method(pool, 'query', async (sql, values) => ({
    rows: values[0] === PHOTO_ID ? [{ id: PHOTO_ID, arquivo }] : [],
  }));
  const app = require('../app');
  const server = app.listen(0);
  t.after(() => server.close());

  const anonymous = await request(server, { path: `/balanca/fotos/${PHOTO_ID}` });
  assert.notEqual(anonymous.statusCode, 200);

  const response = await request(server, { path: `/balanca/fotos/${PHOTO_ID}`, headers: { Cookie: cookie } });
  assert.equal(response.statusCode, 200);
  assert.equal(response.headers['content-type'], 'image/jpeg');
  assert.equal(response.headers['x-content-type-options'], 'nosniff');
  assert.match(response.headers['cache-control'], /^private/);
  assert.deepEqual(response.buffer, jpeg('servida'));

  const missing = await request(server, { path: '/balanca/fotos/nao-existe', headers: { Cookie: cookie } });
  assert.equal(missing.statusCode, 404);
  assert.ok(fs.existsSync(path.join(dir, arquivo)));
});

